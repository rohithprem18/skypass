"""Build the explanatory diagrams for the papers.

Compiles the TikZ sources in this folder to vector PDFs (standalone class, so
the lettering is the same Computer Modern / Latin Modern family as the paper)
and writes the quota-versus-budget illustration from a small table here.

Usage:
    python experiments/diagrams/build_diagrams.py [--out DIR]

Output: arch.pdf, passfind.pdf, quota_budget.pdf, geometry.pdf, unet.pdf
(in --out, default this folder).
The Springer manuscript uses them as Fig1, Fig2 and Fig5; copy and rename after
building (see final_paper/README.md).
"""
from __future__ import annotations

import argparse
import os
import shutil
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))

# --------------------------------------------------------------------------
# Quota versus budget. Illustrative: ten nights, each split into evening,
# midnight and late; cloud persists through a night, which is the measured
# property (between-night variation 2.2x within-night) the figure explains.
#   c = clear, p = partly cloudy, o = overcast
NIGHTS = ["ooo", "oop", "ccc", "ooo", "ccp", "pcp", "ooo", "ccc", "opo", "ppc"]
BUDGET_NIGHTS = [2, 4, 5, 7, 9]          # the five nights forecast clearest
FILL = {"c": "clear", "p": "partly", "o": "overcast"}


def quota_budget_tex() -> str:
    dx, cell_w, cell_h = 1.08, 0.92, 0.30
    rows = [("Nightly quota", "three every night", 0.0, list(range(10))),
            ("Window budget", "may skip nights", -1.75, BUDGET_NIGHTS)]
    out = [r"""% Nightly quota versus window budget. Illustrative sky pattern, not data.
% Generated by experiments/diagrams/build_diagrams.py -- edit the table there.
\documentclass[border=4pt]{standalone}
\usepackage{tikz}
\definecolor{plan}{HTML}{E69F00}
\definecolor{orbit}{HTML}{0072B2}
\definecolor{src}{HTML}{666666}
\colorlet{clear}{orbit!24}
\colorlet{partly}{src!30}
\colorlet{overcast}{src!65}
\begin{document}
\begin{tikzpicture}[font=\footnotesize]"""]
    for name, note, y0, used in rows:
        out.append(rf"\node[anchor=east, align=right] at (-0.2,{y0 - 0.45:.2f}) "
                   rf"{{\textbf{{{name}}}\\{{\scriptsize\color{{src}}{note}}}}};")
        hits = total = 0
        for n, pattern in enumerate(NIGHTS):
            x = n * dx
            for k, ch in enumerate(pattern):
                y = y0 - k * cell_h
                out.append(rf"\fill[{FILL[ch]}] ({x:.2f},{y - cell_h:.2f}) "
                           rf"rectangle ({x + cell_w:.2f},{y:.2f});")
                if n in used:
                    total += 1
                    hits += ch == "c"
                    out.append(rf"\fill[plan] ({x + cell_w / 2:.2f},{y - cell_h / 2:.2f}) "
                               r"circle (2.6pt);")
            if n in used:
                pass
        out.append(rf"\node[anchor=west, align=left, font=\scriptsize] at "
                   rf"({10 * dx - 0.05:.2f},{y0 - 0.45:.2f}) "
                   rf"{{{hits} of {total}\\observations\\clear}};")
    for n in range(10):
        out.append(rf"\node[font=\scriptsize, text=src] at ({n * dx + cell_w / 2:.2f},0.22) "
                   rf"{{night {n + 1}}};")
    ly = -1.75 - 3 * cell_h - 0.45
    legend = [("clear", "clear", 1.5), ("partly", "partly cloudy", 2.6),
              ("overcast", "overcast", 2.0)]
    x = 0.0
    for col, text, width in legend:
        out.append(rf"\fill[{col}] ({x:.2f},{ly - 0.12:.2f}) rectangle ({x + 0.35:.2f},{ly + 0.12:.2f});")
        out.append(rf"\node[anchor=west, font=\scriptsize] at ({x + 0.42:.2f},{ly:.2f}) {{{text}}};")
        x += width
    out.append(rf"\fill[plan] ({x + 0.17:.2f},{ly:.2f}) circle (2.6pt);")
    out.append(rf"\node[anchor=west, font=\scriptsize] at ({x + 0.35:.2f},{ly:.2f}) "
               r"{one observation (evening, midnight, late)};")
    out.append(r"\end{tikzpicture}" + "\n" + r"\end{document}" + "\n")
    return "\n".join(out)


def compile_tex(name: str, out_dir: str) -> str:
    r = subprocess.run(["tectonic", "-X", "compile", f"{name}.tex"], cwd=HERE,
                       capture_output=True, text=True)
    pdf = os.path.join(HERE, f"{name}.pdf")
    if r.returncode != 0 or not os.path.exists(pdf):
        sys.exit(f"{name}.tex failed:\n{r.stderr[-1500:]}")
    if os.path.abspath(out_dir) != HERE:
        shutil.copy(pdf, os.path.join(out_dir, f"{name}.pdf"))
    return os.path.join(out_dir, f"{name}.pdf")


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--out", default=HERE)
    a = ap.parse_args()
    os.makedirs(a.out, exist_ok=True)
    with open(os.path.join(HERE, "quota_budget.tex"), "w", encoding="utf-8", newline="\n") as fh:
        fh.write(quota_budget_tex())
    for name in ("arch", "passfind", "quota_budget", "geometry", "unet"):
        print("  ->", compile_tex(name, a.out))


if __name__ == "__main__":
    main()
