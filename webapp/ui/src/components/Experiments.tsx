import { useState } from 'react';
import { EXPERIMENTS } from '../lib/research';

/* A technical index, not a gallery. Rows separated by hairlines, numbered
 * because the experiments genuinely run in sequence -- each one depends on the
 * previous being sound. Expanding a row is the only interaction. */

export function Experiments() {
  const [open, setOpen] = useState<string | null>(null);

  return (
    <section className="band">
      <div className="wrap pad-lg">
        <header className="sec-head">
          <h1 className="t-page">Experiments</h1>
          <p className="t-body muted sec-lede">
            Eight experiments, each answering one question about the system.
            Every figure is regenerated from archived inputs, so the numbers here
            are the numbers in the paper.
          </p>
        </header>

        <ol className="exps">
          {EXPERIMENTS.map((e) => {
            const on = open === e.id;
            return (
              <li key={e.id} className="exp">
                <button type="button"
                  className={'exp-row' + (on ? ' is-open' : '')}
                  aria-expanded={on}
                  onClick={() => setOpen(on ? null : e.id)}>
                  <span className="exp-n num">
                    <span className="exp-sq" aria-hidden="true" />
                    {e.id}
                  </span>

                  <span className="exp-body">
                    <span className="exp-title">{e.title}</span>
                    <span className="t-meta exp-method">{e.method}</span>
                  </span>

                  <span className="exp-findings">
                    {e.findings.map(([k, v]) => (
                      <span key={k} className="metric">
                        <span className="metric-k">{k}</span>
                        <span className="exp-v num">{v}</span>
                      </span>
                    ))}
                  </span>

                  <span className="exp-cta">
                    {on ? 'Hide' : 'View experiment'}{' '}
                    <span aria-hidden="true">{on ? '↑' : '→'}</span>
                  </span>
                </button>

                {on && (
                  <div className="exp-detail">
                    <p className="t-body">{e.method}.</p>
                    <dl className="exp-detail-facts">
                      {e.findings.map(([k, v]) => (
                        <div key={k} className="metric">
                          <dt className="metric-k">{k}</dt>
                          <dd className="metric-v num">{v}</dd>
                        </div>
                      ))}
                    </dl>
                    <p className="t-meta">
                      Source: <span className="num">
                        results/exp{Number(e.id)}_*.json
                      </span> · regenerated by <span className="num">
                        experiments/exp{Number(e.id)}_*.py
                      </span>
                    </p>
                  </div>
                )}
              </li>
            );
          })}
        </ol>
      </div>
    </section>
  );
}
